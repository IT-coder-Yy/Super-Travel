  const candidate = formal.data.candidates[0];
  await openPool(page);
  await page.locator('#insert-trip-candidate-' + candidate.id).click();
  await page.route('**/trip/candidates/slots', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: { message: '固定测试空档查询失败，请重试。' } }) }), { times: 1 });
