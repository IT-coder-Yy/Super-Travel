  await screenshotSizes(page, 'slots-unknown');
  await expect(page.getByRole('button', { name: '排入草稿', exact: true })).toBeEnabled();
  await page.getByLabel('停留时长（分钟）', { exact: true }).fill('90');
  await expect(page.getByRole('radio')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '排入草稿', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '检查可用时段', exact: true }).click();
  await page.getByRole('radio').first().check();
  await page.getByLabel('目标日期', { exact: true }).selectOption('2');
  await expect(page.getByRole('radio')).toHaveCount(0);
  expect((await trip.read()).revision).toBe(formal.revision);
  expect((await trip.read()).data.draft).toBeNull();
  // Isolated fictional saved-data setup: fill day 1 completely, not real API evidence.
  formal.data.days[0].activities[0].time = '00:00';
  formal.data.days[0].activities[0].duration = '约 720 分钟';
  formal.data.days[0].activities[1].time = '12:00';
